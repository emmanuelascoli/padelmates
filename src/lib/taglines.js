// ── Sélection déterministe par hash de l'ID de session ───────
// La même session donne toujours la même phrase, peu importe
// combien de fois on clique sur "Partager".
export function getTagline(sessionId) {
  if (!sessionId) return TAGLINES[0]
  const hash = sessionId
    .split('')
    .reduce((acc, c) => (acc * 31 + c.charCodeAt(0)) & 0xfffffff, 0)
  return TAGLINES[hash % TAGLINES.length]
}
